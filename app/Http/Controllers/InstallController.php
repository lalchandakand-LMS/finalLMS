<?php

namespace App\Http\Controllers;

use App\Models\User;
use Illuminate\Http\RedirectResponse;
use Illuminate\Http\Request;
use Illuminate\Support\Facades\Artisan;
use Illuminate\Support\Facades\DB;
use Illuminate\Support\Facades\Log;
use Illuminate\Support\Facades\Schema;
use Illuminate\Support\Str;
use Illuminate\Validation\Rules\Password;
use Illuminate\View\View;
use RuntimeException;
use Throwable;

class InstallController extends Controller
{
    public function index(): View
    {
        abort_if($this->isInstalled(), 404);

        return view('install.index');
    }

    public function install(Request $request): RedirectResponse
    {
        abort_if($this->isInstalled(), 404);

        $validated = $request->validate([
            'site_name' => ['required', 'string', 'max:120'],
            'app_url' => ['required', 'url', 'regex:/^https:\\/\\//i', 'max:255'],
            'db_host' => ['required', 'string', 'max:255'],
            'db_port' => ['required', 'integer', 'between:1,65535'],
            'db_database' => ['required', 'string', 'max:128'],
            'db_username' => ['required', 'string', 'max:128'],
            'db_password' => ['nullable', 'string', 'max:255'],
            'admin_name' => ['required', 'string', 'max:255'],
            'admin_email' => ['required', 'email', 'max:255'],
            'admin_password' => ['required', 'confirmed', Password::min(12)],
        ]);

        $envPath = base_path('.env');
        $templatePath = base_path('deployment/.env.example');

        if (is_file($envPath)) {
            $existing = file_get_contents($envPath) ?: '';
            if (! str_contains($existing, '# Generated by Aloms LMS secure installer')) {
                return back()->withInput($request->except(['db_password', 'admin_password', 'admin_password_confirmation']))
                    ->withErrors(['installer' => 'An existing .env file was found. The installer will not overwrite it. Remove it only if you are preparing a fresh installation.']);
            }
        }

        if (! is_file($templatePath) || ! is_writable(base_path())) {
            return back()->withInput($request->except(['db_password', 'admin_password', 'admin_password_confirmation']))
                ->withErrors(['installer' => 'The application root is not ready for installation. Check deployment files and folder permissions.']);
        }

        $lockPath = storage_path('framework/install.lock');
        $lock = @fopen($lockPath, 'c');

        if (! $lock || ! flock($lock, LOCK_EX | LOCK_NB)) {
            if (is_resource($lock)) {
                fclose($lock);
            }

            return back()->withErrors(['installer' => 'Another installation attempt is running. Please wait and try again.']);
        }

        try {
            if ($this->isInstalled()) {
                flock($lock, LOCK_UN);
                fclose($lock);
                abort(404);
            }

            $template = file_get_contents($templatePath);
            if ($template === false) {
                throw new RuntimeException('Unable to read the environment template.');
            }

            $key = 'base64:'.base64_encode(random_bytes(32));
            $values = [
                'APP_NAME' => $this->dotenvValue($validated['site_name']),
                'APP_ENV' => 'production',
                'APP_DEBUG' => 'false',
                'APP_URL' => $this->dotenvValue(rtrim($validated['app_url'], '/')),
                'APP_KEY' => $this->dotenvValue($key),
                'APP_INSTALLED' => 'false',
                'DB_CONNECTION' => 'mysql',
                'DB_HOST' => $this->dotenvValue($validated['db_host']),
                'DB_PORT' => (string) $validated['db_port'],
                'DB_DATABASE' => $this->dotenvValue($validated['db_database']),
                'DB_USERNAME' => $this->dotenvValue($validated['db_username']),
                'DB_PASSWORD' => $this->dotenvValue($validated['db_password'] ?? ''),
                'SESSION_DRIVER' => 'file',
                'APP_LOCALE' => 'en',
                'APP_FALLBACK_LOCALE' => 'en',
            ];

            $environment = "# Generated by Aloms LMS secure installer. Keep this file private.\n".$template;
            foreach ($values as $name => $value) {
                $pattern = '/^'.preg_quote($name, '/').'=.*/m';
                $replacement = $name.'='.$value;
                $updated = preg_replace($pattern, $replacement, $environment, 1, $count);
                if ($updated === null || $count !== 1) {
                    throw new RuntimeException('The environment template is missing '.$name.'.');
                }
                $environment = $updated;
            }

            config([
                'app.name' => $validated['site_name'],
                'app.url' => rtrim($validated['app_url'], '/'),
                'app.key' => $key,
                'app.installed' => false,
                'database.default' => 'mysql',
                'database.connections.mysql.host' => $validated['db_host'],
                'database.connections.mysql.port' => (string) $validated['db_port'],
                'database.connections.mysql.database' => $validated['db_database'],
                'database.connections.mysql.username' => $validated['db_username'],
                'database.connections.mysql.password' => $validated['db_password'] ?? '',
                'session.driver' => 'file',
            ]);

            DB::purge('mysql');
            DB::connection('mysql')->getPdo();

            // The fresh installer must never share a database with another app or a partial install.
            // SHOW FULL TABLES includes both base tables and views on MySQL/MariaDB.
            if (DB::connection('mysql')->select('SHOW FULL TABLES') !== []) {
                throw new RuntimeException('The selected database is not empty. Create a brand-new empty database and try again.');
            }

            // Persist credentials only after connectivity and the empty-database guard pass.
            $this->writeEnvironment($envPath, $environment);

            if (Artisan::call('migrate', ['--force' => true]) !== 0) {
                throw new RuntimeException('Database migrations did not complete.');
            }

            if (Artisan::call('db:seed', ['--force' => true]) !== 0) {
                throw new RuntimeException('Default application settings could not be created.');
            }

            User::create([
                'name' => $validated['admin_name'],
                'email' => $validated['admin_email'],
                'password' => $validated['admin_password'],
                'role' => 'admin',
                'email_verified_at' => now(),
            ]);

            $environment = preg_replace('/^APP_INSTALLED=.*/m', 'APP_INSTALLED=true', $environment, 1);
            if ($environment === null) {
                throw new RuntimeException('Unable to finalize installation settings.');
            }
            $this->writeEnvironment($envPath, $environment);
            config(['app.installed' => true]);

            $installedDirectory = storage_path('app');
            if (! is_dir($installedDirectory) && ! mkdir($installedDirectory, 0750, true) && ! is_dir($installedDirectory)) {
                throw new RuntimeException('Unable to create the installation lock directory.');
            }
            file_put_contents(storage_path('app/installed.lock'), now()->toIso8601String(), LOCK_EX);
            @chmod(storage_path('app/installed.lock'), 0600);

            return redirect()->route('login')->with('status', 'Installation completed. Sign in with your administrator account.');
        } catch (Throwable $exception) {
            Log::error('LMS web installation failed.', [
                'exception' => $exception::class,
                'message' => $exception->getMessage(),
            ]);

            return back()->withInput($request->except(['db_password', 'admin_password', 'admin_password_confirmation']))
                ->withErrors(['installer' => 'Installation failed. Check storage/logs/laravel.log and verify that the database is empty and its credentials are correct.']);
        } finally {
            flock($lock, LOCK_UN);
            fclose($lock);
        }
    }

    private function isInstalled(): bool
    {
        return is_file(storage_path('app/installed.lock'))
            || (is_file(base_path('.env')) && (bool) config('app.installed', true));
    }

    private function dotenvValue(string $value): string
    {
        return '"'.str_replace(["\\", '"', "\n", "\r"], ["\\\\", '\\"', '\\n', '\\r'], $value).'"';
    }

    private function writeEnvironment(string $path, string $contents): void
    {
        $temporary = $path.'.'.Str::random(12).'.tmp';
        if (file_put_contents($temporary, $contents, LOCK_EX) === false) {
            throw new RuntimeException('Unable to write the environment file.');
        }

        @chmod($temporary, 0600);
        if (! rename($temporary, $path)) {
            @unlink($temporary);
            throw new RuntimeException('Unable to activate the environment file.');
        }
        @chmod($path, 0600);
    }
}
